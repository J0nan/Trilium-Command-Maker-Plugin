import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(root, 'src');
const distDir = path.join(root, 'dist');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

// Dependency order does not matter: modules are registered first and executed
// lazily on first require.
const MODULES = [
    'i18n', 'render', 'parse', 'sections', 'toolfile', 'prompt', 'model', 'version',
    'styles', 'dom', 'sourcePicker', 'backend', 'ui', 'runtime'
];
const REQUIRE_RE = /require\(\s*['"]\.\/([\w-]+)(?:\.js)?['"]\s*\)/g;

function inlineRequires(code) {
    return code.replace(REQUIRE_RE, function (_match, name) {
        return '__require("' + name + '")';
    });
}

function read(name) {
    return fs.readFileSync(path.join(sourceDir, name + '.js'), 'utf8');
}

function assertKnownRequires(code, origin) {
    REQUIRE_RE.lastIndex = 0;
    let match = REQUIRE_RE.exec(code);
    while (match !== null) {
        if (MODULES.indexOf(match[1]) === -1) {
            throw new Error(origin + ' requires unknown module "' + match[1] + '"');
        }
        match = REQUIRE_RE.exec(code);
    }
}

function buildBundle() {
    const versionSource = read('version');
    const expected = "const VERSION = '" + pkg.version + "';";
    if (versionSource.indexOf(expected) === -1) {
        throw new Error('src/version.js must declare ' + expected + ' to match package.json');
    }

    const definitions = MODULES.map(function (name) {
        const code = read(name);
        assertKnownRequires(code, name);
        return '__def(' + JSON.stringify(name) + ', function (module, exports, __require) {\n'
            + inlineRequires(code)
            + '\n});';
    });

    const entry = read('entry');
    assertKnownRequires(entry, 'entry');

    return [
        '/* Command Maker - generated by tools/build.mjs. Do not edit by hand. */',
        '(function () {',
        '    "use strict";',
        '    var registry = {};',
        '    function __def(name, factory) { registry[name] = { factory: factory, exports: null, loaded: false }; }',
        '    function __require(name) {',
        '        var module = registry[name];',
        '        if (!module) { throw new Error("Unknown module: " + name); }',
        '        if (!module.loaded) {',
        '            var container = { exports: {} };',
        '            module.factory(container, container.exports, __require);',
        '            module.exports = container.exports;',
        '            module.loaded = true;',
        '        }',
        '        return module.exports;',
        '    }',
        definitions.join('\n'),
        inlineRequires(entry),
        '})();',
        ''
    ].join('\n');
}

function buildInstaller(bundle, version) {
    const templatePath = path.join(root, 'tools', 'install-template.js');
    const template = fs.readFileSync(templatePath, 'utf8');
    if (template.indexOf('__BUNDLE__') === -1) {
        throw new Error('install-template.js is missing the __BUNDLE__ placeholder');
    }
    if (template.indexOf('__VERSION__') === -1) {
        throw new Error('install-template.js is missing the __VERSION__ placeholder');
    }
    assertInstallerLabels(template);
    return template
        .replace('__BUNDLE__', function () {
            return JSON.stringify(bundle);
        })
        .replace('__VERSION__', version || pkg.version);
}

/**
 * The installer runs on the backend before the bundle exists, so it hard-codes
 * the label names it needs. Fail the build when one of them drifts away from
 * Model.LABELS: a typo would otherwise create a second, unfindable root note.
 * `cmPlugin` and `cmShortcut` are installer-only attributes the plugin never
 * reads, so they are not part of Model.LABELS.
 */
const INSTALLER_ONLY_LABELS = ['cmPlugin', 'cmShortcut'];

function assertInstallerLabels(template) {
    const model = fs.readFileSync(path.join(sourceDir, 'model.js'), 'utf8');
    const installerLabel = /var\s+[A-Z_]+\s*=\s*'(cm[A-Za-z0-9]+)'/g;
    let match = installerLabel.exec(template);
    while (match !== null) {
        const label = match[1];
        if (INSTALLER_ONLY_LABELS.indexOf(label) === -1 && model.indexOf("'" + label + "'") === -1) {
            throw new Error('install-template.js uses label "' + label + '", which src/model.js does not define');
        }
        match = installerLabel.exec(template);
    }
}

function main() {
    const bundle = buildBundle();
    const installer = buildInstaller(bundle);

    fs.mkdirSync(distDir, { recursive: true });
    fs.writeFileSync(path.join(distDir, 'command-maker.js'), bundle, 'utf8');
    fs.writeFileSync(path.join(distDir, 'install.js'), installer, 'utf8');

    // Fail fast on syntax errors instead of shipping a broken note.
    new Function(bundle);
    new Function(installer);

    console.log('built dist/command-maker.js (' + bundle.length + ' bytes)');
    console.log('built dist/install.js (' + installer.length + ' bytes)');
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : '';
if (invokedPath === fileURLToPath(import.meta.url)) {
    main();
}

export { buildBundle, buildInstaller, assertInstallerLabels, main };